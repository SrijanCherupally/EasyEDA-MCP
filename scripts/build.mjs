import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execSync } from 'node:child_process';

// 1. in-editor runtime (.eext) first, so the server can embed it for self-updates
execSync('node scripts/build-extension.mjs', { stdio: 'inherit' });
mkdirSync('src/generated', { recursive: true });
const manifest = readFileSync('extension/extension.json', 'utf8');
const code = readFileSync('extension/dist/index.js', 'utf8');
writeFileSync(
	'src/generated/runtime.ts',
	`// generated by scripts/build.mjs — do not edit\nexport const RUNTIME_MANIFEST = ${JSON.stringify(manifest)};\nexport const RUNTIME_CODE = ${JSON.stringify(code)};\nexport const RUNTIME_VERSION = ${JSON.stringify(JSON.parse(manifest).version)};\n`,
);

// 2. server, hub, cli
const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
await build({
	entryPoints: { index: 'src/index.ts', hub: 'src/hub.ts', cli: 'src/cli.ts' },
	outdir: 'dist',
	bundle: true,
	platform: 'node',
	format: 'esm',
	target: 'node20',
	packages: 'external',
	loader: { '.edajs': 'text' },
	define: { __PKG_VERSION__: JSON.stringify(pkg.version) },
	banner: { js: '' },
	logLevel: 'warning',
});
console.log('server built', pkg.version);
